def weather_code_to_chinese(code):
    """
    将 WMO 天气代码转换为中文天气描述。
    """

    if code is None:
        return "未知天气"

    try:
        code = int(code)
    except (TypeError, ValueError):
        return "未知天气"

    weather_codes = {
        0: "晴朗",

        1: "大致晴朗",
        2: "局部多云",
        3: "阴天",

        45: "雾",
        48: "雾凇",

        51: "小毛毛雨",
        53: "中等毛毛雨",
        55: "较强毛毛雨",

        56: "轻度冻毛毛雨",
        57: "较强冻毛毛雨",

        61: "小雨",
        63: "中雨",
        65: "大雨",

        66: "轻度冻雨",
        67: "较强冻雨",

        71: "小雪",
        73: "中雪",
        75: "大雪",

        77: "雪粒",

        80: "小阵雨",
        81: "中等阵雨",
        82: "强阵雨",

        85: "小阵雪",
        86: "强阵雪",

        95: "雷暴",
        96: "雷暴伴有小冰雹",
        99: "雷暴伴有大冰雹"
    }

    return weather_codes.get(
        code,
        f"未知天气代码（{code}）"
    )